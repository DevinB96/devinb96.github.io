#!/usr/bin/env node
// Builds the Karis Smart Cleaning website from content/*.json and src/ into static HTML.
//
//   node build.mjs                       preview build (noindex) into ../../karis-smart-cleaning
//   node build.mjs --env production      launch build into ./dist (needs siteUrl and formEndpoint)
//   node build.mjs --out some/dir        override the output folder
//   --site-url / --form-endpoint         override those settings for one build (e.g. a staging domain)
//
// No dependencies: Node 18 or later is all that is needed.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { render } from './src/layout.mjs';
import home from './src/pages/home.mjs';
import { hub, servicePage } from './src/pages/services.mjs';
import { areas, about, quote, thanks, privacy, cookies, notFound } from './src/pages/other.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const MARKER = '.karis-build';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
const envName = args.env || 'preview';

const fail = (msg) => { console.error(`Build stopped: ${msg}`); process.exit(1); };
const readJson = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'content', f), 'utf8'));
const site = readJson('site.json');
const services = readJson('services.json');
const rooms = readJson('rooms.json');
const env = { ...site.environments[envName] };
if (!site.environments[envName]) fail(`unknown environment "${envName}". Use one of: ${Object.keys(site.environments).join(', ')}.`);
if (args['site-url']) env.siteUrl = args['site-url'];
if (args['form-endpoint']) env.formEndpoint = args['form-endpoint'];
if (!env.siteUrl) fail(`environments.${envName}.siteUrl is empty in content/site.json. Set the live domain first.`);
if (!env.formEndpoint) fail(`environments.${envName}.formEndpoint is empty in content/site.json. The quote form needs somewhere to send enquiries.`);
const siteUrl = env.siteUrl.endsWith('/') ? env.siteUrl : env.siteUrl + '/';

const outDir = path.resolve(ROOT, args.out || env.out);
const srcAssets = path.join(ROOT, 'src', 'assets');

// Only ever wipe a folder this script created.
if (fs.existsSync(outDir)) {
  const entries = fs.readdirSync(outDir);
  if (entries.length && !entries.includes(MARKER)) fail(`refusing to overwrite ${outDir}: it was not created by this build.`);
  fs.rmSync(outDir, { recursive: true, force: true });
}
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, MARKER), `Generated by clients/karis-smart-cleaning/build.mjs (${envName}). Do not edit by hand.\n`);

// Cache-busting: ?v=<content hash> on CSS and JS so updates show immediately after deploy.
const hashes = {};
const hashOf = (rel) => (hashes[rel] ??= crypto.createHash('sha1').update(fs.readFileSync(path.join(srcAssets, rel))).digest('hex').slice(0, 8));
const asset = (rel) => `assets/${rel}?v=${hashOf(rel)}`;

const now = new Date();
const ctx = {
  site, services, rooms, env, envName, siteUrl, asset,
  basePath: new URL(siteUrl).pathname,
  buildYear: now.getFullYear(),
  buildDate: now.toISOString().slice(0, 10),
  buildDateLong: now.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' }),
};

const pages = [home, hub, ...services.map(servicePage), areas, about, quote, thanks, privacy, cookies, notFound];
const written = [];
for (const def of pages) {
  const page = { ...def, ...def.render.call(def, ctx) };
  const file = path.join(outDir, def.file || path.join(def.path, 'index.html'));
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, render(ctx, page));
  written.push({ path: def.path, noindex: page.noindex || def.file === '404.html' });
}

fs.cpSync(srcAssets, path.join(outDir, 'assets'), { recursive: true });

const indexable = written.filter((p) => !p.noindex);
fs.writeFileSync(path.join(outDir, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((p) => `  <url><loc>${siteUrl}${p.path}</loc><lastmod>${ctx.buildDate}</lastmod></url>`).join('\n')}
</urlset>
`);
fs.writeFileSync(path.join(outDir, 'robots.txt'), env.noindex
  ? 'User-agent: *\nDisallow: /\n'
  : `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}sitemap.xml\n`);
fs.writeFileSync(path.join(outDir, 'site.webmanifest'), JSON.stringify({
  name: site.business.name,
  short_name: 'Karis',
  start_url: './',
  display: 'browser',
  background_color: '#f5f1ea',
  theme_color: '#17352f',
  icons: [{ src: 'assets/img/icon-192.png', sizes: '192x192', type: 'image/png' }, { src: 'assets/img/logo-512.png', sizes: '512x512', type: 'image/png' }],
}, null, 2));

console.log(`Built ${written.length} pages (${indexable.length} in sitemap) for "${envName}" -> ${path.relative(process.cwd(), outDir) || '.'}`);
